def _pixel_type_letters():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(os.path.dirname(here))
    path = os.path.join(root, "onlystage_3", "pixel_type.py")
    src = open(path, encoding="utf-8").read()
    # reuse the table without importing PIL-dependent code
    start = src.index("LETTERS=dict(")
    end = src.index(".split()))", start) + len(".split()))")
    ns = {}
    exec(src[start:end], ns)
    return ns["LETTERS"]


def glyphs():
    """returns list of 128 glyphs, each a list of 8 row bytes (bit 7 = leftmost pixel)."""
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(os.path.dirname(here))
    pt_path = os.path.join(root, "onlystage_3", "pixel_type.py")
    if not os.path.exists(pt_path):
        mem_path = os.path.join(os.path.dirname(here), "mem", "font.mem")
        vals = [int(l.strip(), 16) for l in open(mem_path, encoding="utf-8") if l.strip() and not l.startswith("//")]
        return [vals[i * 8:(i + 1) * 8] for i in range(128)]
    g = [[0] * 8 for _ in range(128)]
    for ch, cols in _pixel_type_letters().items():
        if ch == " ":
            continue
        b = bytes.fromhex(cols)
        rows = [0] * 8
        for x, bits in enumerate(b):
            for y in range(7):
                if bits & (1 << y):
                    rows[y] |= 0x80 >> (x + 1)
        g[ord(ch)] = rows
    for ch, spec in ROWS.items():
        rows = [0] * 8
        for y, r in enumerate(spec.split()):
            for x, c in enumerate(r):
                if c == "1":
                    rows[y] |= 0x80 >> (x + 1)
        g[ord(ch)] = rows
    for code, (_, spec) in SYM.items():
        rows = []
        for r in spec.split():
            v = 0
            for x, c in enumerate(r[:8]):
                if c == "#":
                    v |= 0x80 >> x
            rows.append(v)
        g[code] = rows
    return g


if __name__ == "__main__":
    from PIL import Image
    gl = glyphs()
    im = Image.new("L", (16 * 9, 8 * 9), 40)
    for i, rows in enumerate(gl):
        for y, v in enumerate(rows):
            for x in range(8):
                if v & (0x80 >> x):
                    im.putpixel(((i % 16) * 9 + x, (i // 16) * 9 + y), 255)
    im.resize((im.width * 4, im.height * 4), Image.NEAREST).save(sys.argv[1] if len(sys.argv) > 1 else "font.png")
