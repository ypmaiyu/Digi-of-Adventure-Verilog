#!/usr/bin/env python3
"""make_xdc.py - builds constraints/nexys_a7_100t.xdc by UN-commenting the needed lines of
Digilent's official Nexys-A7-100T-Master.xdc (github.com/Digilent/digilent-xdc), so every
pin location and I/O standard comes from the board vendor, not from memory."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "constraints", "Nexys-A7-100T-Master.xdc.orig")
dst = os.path.join(here, "..", "constraints", "nexys_a7_100t.xdc")
WANT = re.compile(r"get_ports \{ ?(CLK100MHZ|CPU_RESETN|SW\[\d+\]|LED\[\d+\]|LED16_[RGB]|LED17_[RGB]|C[A-G]|DP|AN\[\d\]|"
                  r"BTN[CUDLR]|VGA_[RGB]\[\d\]|VGA_HS|VGA_VS) ?\}")
out = ["## nexys_a7_100t.xdc - generated by tools/make_xdc.py from Digilent's Nexys-A7-100T-Master.xdc",
       "## (commit c8644a9 of github.com/Digilent/digilent-xdc). Do not edit pins by hand.", ""]
for line in open(src):
    s = line.rstrip("\n")
    if s.startswith("#set_property") and WANT.search(s):
        out.append(s[1:])
    elif s.startswith("#create_clock") and "CLK100MHZ" in s:
        out.append(s[1:])
    elif s.startswith("##") and len(s) < 60:
        out.append(s)
out += ["",
        "## configuration (Nexys A7 board files): 3.3 V configuration bank, SPI x4 flash",
        "set_property CFGBVS VCCO [current_design]",
        "set_property CONFIG_VOLTAGE 3.3 [current_design]",
        "set_property BITSTREAM.CONFIG.SPI_BUSWIDTH 4 [current_design]",
        "",
        "## the push buttons, switches and the reset button are asynchronous inputs (synchronised in RTL)",
        "set_false_path -from [get_ports {BTN* SW[*] CPU_RESETN}]",
        "## slow outputs (LEDs, 7-segment) - no timing requirement",
        "set_false_path -to [get_ports {LED[*] LED16_* LED17_* C[A-G] DP AN[*]}]"]
open(dst, "w").write("\n".join(out) + "\n")
print("wrote", dst, sum(1 for l in out if l.startswith("set_property -dict")), "pins")
