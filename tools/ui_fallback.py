def make_s2_namespace():
    item_objs = [types.SimpleNamespace(id=i, part=p, name=n, clue=c) for i, p, n, c in S2_ITEM_SPOTS]
    hint_objs = [types.SimpleNamespace(id=i, title=t, text=x) for i, t, x in S2_HINT_SPOTS]
    sinks = [f"k{i}" for i in range(54)]
    return types.SimpleNamespace(
        PARTS=S2_PARTS,
        PART_SHORT=S2_PART_SHORT,
        INTRO_LINES=S2_INTRO_LINES,
        ROUNDS=3,
        CHAR_NAME={1: "C", 2: "P", 3: "E", 4: "-", 5: "3", 6: "9"},
        bits=lambda k: ((k >> 2) & 1, (k >> 1) & 1, k & 1),
        ITEM_SPOTS=item_objs,
        HINT_SPOTS=hint_objs,
        RAIL_LINES=[("1", 120), ("0", 244), ("1", 296), ("0", 476)],
        IC_X={"U1": 190, "U2": 400, "U3": 190, "U4": 400},
        IC_Y={"U1": 150, "U2": 150, "U3": 330, "U4": 330},
        IC_TYPE={"U1": "74HC04", "U2": "74HC08", "U3": "74HC32", "U4": "74HC32"},
        BODY_H=64,
        SEGS="abcdefg",
        UNITS=["U1", "U2", "U3", "U4"],
        SRC_POS=S2_SRC_POS,
        src_color=lambda src: S2_SRC_COLORS[src],
        SINKS=sinks,
        SINK_POS={sinks[i]: S2_SINK_POS[i] for i in range(54)},
        SRC_LIST=S2_SRC_IDS,
    )
