#!/usr/bin/env python3
"""s3_tables.py - Stage 3 data for the RTL, taken from the game's own code
(onlystage_3/level.py, game.py, settings.py, render.py):
    rtl/gen/s3_tables.vh
        s3_col(level, column)    -> {water[10:0], solid[10:0]}   bit r = cell at height r (from the bottom)
        s3_animal(stage, i)      -> spawn record of animal i (first/second/third_stage_animals())
        S3_NANIMALS_n, S3_BOTTOM_n, ...
Units: tiles (metres). x values are stored x2 (half tiles), heights in tiles.
Run from the repository root:  python3 fpga/tools/s3_tables.py
"""
import os, sys, math
ROOT = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.getcwd()
sys.path.insert(0, ROOT)
import onlystage_3.settings as C
import onlystage_3.game as G
from onlystage_3.level import Level
from onlystage_3.render import spawn_soil_bottom

sys.path.insert(0, os.path.join(ROOT, "fpga", "tools"))
OUT = os.path.join(ROOT, "fpga", "rtl", "gen", "s3_tables.vh")
levels = {n: Level(C.ASSETS / f) for n, f in C.MAPS.items()}

# asset ids (from asset_ids.vh written by asset_compiler.py)
ids = {}
for line in open(os.path.join(ROOT, "fpga", "rtl", "gen", "asset_ids.vh")):
    if line.startswith("localparam [7:0] A_"):
        name = line.split()[2]
        ids[name[2:].lower()] = int(line.split("8'd")[1].rstrip(";\n"))

SPECIES = {"snail": 0, "squirrel": 1, "ant": 2, "goose": 3}
MOTION = {"patrol": 0, "walk": 1, "pop": 2, "fly": 3}
SKINS = {1: C.STAGE_ONE_ANIMALS, 2: C.ANIMALS, 3: C.STAGE_THREE_ANIMALS}

lines = ["// generated by fpga/tools/s3_tables.py from onlystage_3 - do not edit", ""]
# ---------------- column masks ----------------
lines.append("// s3_col(level, col) = {water[10:0], solid[10:0]}; bit r = cell r tiles above the bottom")
lines.append("function [21:0] s3_col;\n  input [1:0] lvl;\n  input [7:0] col;\n  begin\n    case ({lvl, col})")
for n, lv in levels.items():
    for c in range(lv.width):
        s = w = 0
        for b in lv.solids:
            if b.x <= c < b.x + b.w:
                for r in range(int(b.y), int(math.ceil(b.y + b.h))):
                    s |= 1 << r
        for b in lv.water:
            if b.x <= c < b.x + b.w:
                for r in range(int(b.y), int(math.ceil(b.y + b.h))):
                    w |= 1 << r
        if s or w:
            lines.append("      {2'd%d, 8'd%d}: s3_col = {11'h%03X, 11'h%03X};" % (n, c, w & 0x7FF, s & 0x7FF))
lines.append("      default: s3_col = 22'd0;\n    endcase\n  end\nendfunction\n")
for n, lv in levels.items():
    assert all(b.w == 1 and b.h == 1 and b.x == int(b.x) and b.y == int(b.y) for b in lv.solids + lv.water), "non-grid block"

# ---------------- frame bottom (render.draw_frame) ----------------
ref = levels[2]
datum = spawn_soil_bottom(ref, C.SPAWNS[2][0])
for n, lv in levels.items():
    adj = (spawn_soil_bottom(lv, C.SPAWNS[1][0]) - datum) * 32 if n == 1 else 0
    lines.append("localparam signed [10:0] S3_BOTTOM_%d = %d;   // frame row of height 0" % (n, 352 + int(round(adj))))

# ---------------- animals ----------------
def animals(n):
    g = G.Game.__new__(G.Game)
    lst = {1: G.first_stage_animals, 2: G.second_stage_animals, 3: G.third_stage_animals}[n]()
    lv = levels[n]
    for e in lst:                                   # restart(): snap to the nearest surface
        if e.motion in ("walk", "patrol", "pop"):
            tops = lv.surfaces(e.x)
            if tops:
                e.y = min(tops, key=lambda h: abs(h - e.base_y))
            if e.motion == "pop":
                e.base_y = e.y
                e.y -= 1
    return lst

lines.append("// s3_animal(stage, i) = {leader[5:0] (63 = none), active, species[1:0], motion[1:0],")
lines.append("//   x2[9:0], y4[5:0] (y*4), base4[5:0], lo2[9:0], hi2[9:0], trig2[9:0]}  (x2 = x*2, half tiles)")
lines.append("function [62:0] s3_animal;\n  input [1:0] st;\n  input [5:0] i;\n  begin\n    case ({st, i})")
counts = {}
for n in (1, 2, 3):
    lst = animals(n)
    counts[n] = len(lst)
    for i, e in enumerate(lst):
        lead = lst.index(e.leader) if e.leader is not None else 63
        lo, hi = e.bounds if e.bounds else (e.x, e.x)
        def h2(v):
            assert abs(v * 2 - round(v * 2)) < 1e-6, v
            return int(round(v * 2))
        def q4(v):
            assert abs(v * 4 - round(v * 4)) < 1e-6, v
            return int(round(v * 4))
        lines.append("      {2'd%d, 6'd%d}: s3_animal = {6'd%d, 1'b%d, 2'd%d, 2'd%d, 10'd%d, 6'd%d, 6'd%d, 10'd%d, 10'd%d, 10'd%d};"
                     % (n, i, lead, int(e.active), SPECIES[e.species], MOTION[e.motion], h2(e.x), q4(e.y) & 63,
                        q4(e.base_y) & 63, h2(lo), h2(hi), h2(e.trigger)))
lines.append("      default: s3_animal = 63'd0;\n    endcase\n  end\nendfunction")
for n in (1, 2, 3):
    lines.append("localparam [5:0] S3_NANIMALS_%d = %d;" % (n, counts[n]))

# skins: random.choice of the per-stage lists that exist on disk -> asset ids
lines.append("\n// s3_skin(stage, species, k) = asset id of skin k (k wraps over the list)")
lines.append("function [7:0] s3_skin;\n  input [1:0] st;\n  input [1:0] sp;\n  input [2:0] k;\n  reg [2:0] n;\n  begin\n    case ({st, sp})")
for n in (1, 2, 3):
    for sp, si in SPECIES.items():
        names = SKINS[n].get(sp) or C.ANIMALS[sp]
        names = [x for x in names if (C.ASSETS / x).is_file()] or C.ANIMALS[sp]
        aid = [ids["an_" + x[:-4].lower()] for x in names]
        sel = " : ".join("(k %% %d == %d) ? 8'd%d" % (len(aid), j, a) for j, a in enumerate(aid[:-1]))
        expr = (sel + " : " if sel else "") + "8'd%d" % aid[-1]
        lines.append("      {2'd%d, 2'd%d}: s3_skin = %s;   // %s" % (n, si, expr, ", ".join(names)))
lines.append("      default: s3_skin = 8'd0;\n    endcase\n  end\nendfunction")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT, counts)
