ITEM_NAMES = [("NONE", ""), ("HINT", "Hint"), ("BOOST", "Speed Boost"), ("ARMOR", "Armor"),
              ("SHARD", "Armor Shard"), ("SLOW", "Slow"), ("FREEZE", "Freeze"), ("UNDO", "Undo"),
              ("HEART_LOSS", "Heart Loss")]


def build_common(ui, card_descs):
    ui.table("T_TOAST", [(k, (" %s " % t) if t else "") for k, t in TOASTS])
    ui.table("T_ITEM_NAME", ITEM_NAMES)
    ui.table("T_OBTAINED", [(k, ("Obtained: " + t) if t else "") for k, t in ITEM_NAMES])
    ui.table("T_CARD_DESC", card_descs, wrap_chars=36)
    ui.table("T_FORM", [("F0", "Student uniform"), ("F1", "Lab coat"), ("F2", "Graduation gown"),
                        ("F3", "Super Yasai")])

    # ---- HUD: hearts, armor, slow / freeze timers (stage1_demo.draw_hud) ----
    p = ui.program("HUD")
    for i in range(3):
        at = p.if_("C_HEART%d" % i)
        p.char_c(3 + 2 * i, 2, 0x01, (230, 50, 60))
        p.end(at)
        at = p.if_("C_HEART%d" % i, neg=True)
        p.char_c(3 + 2 * i, 2, 0x01, (80, 50, 50))
        p.end(at)
    at = p.if_("C_ARMOR")
    p.char_c(9, 2, 0x04, (80, 180, 255))
    p.text_c(11, 2, "x", (120, 200, 255))
    p.field_c(12, 2, "F_ARMOR_N", (120, 200, 255), 2)
    p.end(at)
    at = p.if_("C_SLOW")
    p.text_c(16, 2, "SLOW", (255, 150, 80))
    p.field_c(21, 2, "F_SLOW_S", (255, 150, 80), 4)
    p.end(at)
    at = p.if_("C_FREEZE")
    p.text_c(25, 2, "FREEZE", (140, 220, 255))
    p.field_c(32, 2, "F_FREEZE_S", (140, 220, 255), 4)
    p.end(at)

    # ---- toast (draw_toast: black box centred at the top) ----
    p = ui.program("TOAST")
    at = p.if_("C_TOAST")
    p.strsel_c(40, 3, "T_TOAST", "F_TOAST", WHITE, center=True, bg=(0, 0, 0))
    p.end(at)

    # ---- card picker (draw_cards). Card pictures are drawn by the line engine. ----
    p = ui.program("CARDS")
    p.ox = 160
    p.ctxt("PICK A CARD", 320, 30, "l")
    for pos in range(3):
        at = p.if_("C_CARD_CUR%d" % pos)
        x = 65 + pos * 180
        p.rect(x - 5, 95 - 5, 180, 180, None, border=WHITE)
        p.end(at)
    at = p.if_("C_CARD_FACE")
    p.rect(56, 300, 528, 110, (30, 35, 45))
    p.sel("T_OBTAINED", "F_CARD_NAME", 320, 306, "l", GOLD, center=True)
    p.sel("T_CARD_DESC", "F_CARD_DESC", 320, 350, "s", (240, 240, 240), center=True, lh=20)
    p.ctxt("BTNC: continue", 320, 424, "m", LBLUE)
    p.end(at)
    at = p.if_("C_CARD_FACE", neg=True)
    p.ctxt("BTNL/BTNR choose   BTNC pick", 320, 360, "m", LBLUE)
    at2 = p.if_("C_CARD_SKIP")                    # Stage 2 optional 4th card can be skipped
    p.ctxt("hold BTNC: skip", 320, 390, "s", DIM_T)
    p.end(at2)
    p.end(at)

    # ---- compact 16:9 overlay strips: title (row 1 inside row 0..1 header) and control help (row 44) ----
    p = ui.program("BAR_TOP")
    p.rect_c(0, 0, 80, 2, (10, 14, 22))
    p.strsel_c(3, 1, "T_BAR_TITLE", "F_BAR_TITLE", (220, 225, 240))
    p.text_c(51, 1, "SW12:Demo", (140, 150, 180))
    p.strsel_c(69, 1, "T_FORM", "F_FORM", (150, 155, 175), center=True)
    p = ui.program("BAR_BOTTOM")
    p.rect_c(0, 44, 80, 1, (10, 14, 22))
    p.strsel_c(3, 44, "T_BAR_HELP", "F_BAR_HELP", (180, 190, 210))

    # ---- SW12 Demo Tool overlay (demo_hub.py) ----
    ui.table("T_DEMO_STG", [
        ("OPEN", "0: Open"), ("S1", "1: Stage 1"), ("C12", "2: Cutscene 1-2"),
        ("S2", "3: Stage 2"), ("C23", "4: Cutscene 2-3"), ("S3", "5: Stage 3"), ("END", "6: Ending")
    ])
    ui.table("T_DEMO_CKPT", [
        ("NONE", "(No checkpoints)"),
        ("S1_0", "S1: Start"), ("S1_1", "S1: 3 puzzles (Round 2)"), ("S1_2", "S1: All 5 (Round 3)"),
        ("S1_3", "S1: Exit door ready"), ("S1_4", "S1: Stage Clear"),
        ("S2_0", "S2: Start"), ("S2_1", "S2: 8 parts (Card 2)"), ("S2_2", "S2: 18 parts (Breadboard)"),
        ("S2_3", "S2: QA Done (Door open)"), ("S2_4", "S2: Stage Clear"),
        ("S3_0", "S3: Part 2 (S4->CB2)"), ("S3_1", "S3: Part 3 (N17->N16)"),
        ("E_0",  "End: Grad summary"), ("E_1",  "End: Career reveal"),
    ])
    ui.table("T_DEMO_ACT", [
        ("NONE", "(No shortcuts)"),
        ("S1_0", "Force wrong door (-1H)"), ("S1_1", "Give 1 Armor"),
        ("S2_0", "Collect all 18 parts"), ("S2_1", "Check bench & 4th card"), ("S2_2", "Give 1 Armor"),
        ("S2_3", "Trigger QA fail (-1H)"), ("S2_4", "Auto-wire breadboard"),
        ("S3_0", "Trigger Graduation (Win)"),
        ("E1", "Ending 1: Fried Grasshopper"), ("E2", "Ending 2: Aircon Tech"), ("E3", "Ending 3: Astronaut"),
        ("E4", "Ending 4: Noodle Seller"), ("E5", "Ending 5: Software Eng"), ("E6", "Ending 6: Lottery Seller"),
        ("E7", "Ending 7: Fisherman"), ("E8", "Ending 8: Pirate"), ("E9", "Ending 9: Subsea Net Eng"),
    ])
    ui.table("T_DEMO_FL", [("RESTART", "Restart current stage"), ("SKIP", "Skip to next stage >>")])
    ui.table("T_DEMO_NOTE", [
        ("NONE", ""),
        ("DONE", "Applied! Flip SW12 DOWN to resume play."),
        ("NOCKPT", "No checkpoints for this scene."),
        ("NOACT", "No shortcuts for this scene."),
        ("STG", "Switched stage! Flip SW12 DOWN to play."),
    ])

    p = ui.program("DEMO_MENU")
    p.rect_c(5, 2, 70, 41, PANEL, border=GOLD)
    p.text_c(40, 4, "DEMO TOOLS  (Flip SW12 DOWN to close)", GOLD, center=True)
    p.text_c(8, 6, "Now:", (170, 200, 255))
    p.strsel_c(13, 6, "T_DEMO_STG", "F_DEMO_CUR_STG", WHITE)
    p.text_c(29, 6, "H:", (170, 200, 255))
    p.field_c(31, 6, "F_DEMO_CUR_H", GREEN, 1)
    p.text_c(34, 6, "Form:", (170, 200, 255))
    p.strsel_c(40, 6, "T_FORM", "F_DEMO_CUR_F", GOLD)

    rows = [
        ("Stage",      "T_DEMO_STG",  "F_DEMO_STG",  None),
        ("Checkpoint", "T_DEMO_CKPT", "F_DEMO_CKPT", None),
        ("Shortcut",   "T_DEMO_ACT",  "F_DEMO_ACT",  None),
        ("Hearts",     None,          "F_DEMO_H",    "1-3"),
        ("Form",       "T_FORM",      "F_DEMO_F",    None),
        ("Stage Flow", "T_DEMO_FL",   "F_DEMO_FL",   None),
    ]
    for r, (lbl, tbl, fld, _) in enumerate(rows):
        y = 9 + r * 4
        at = p.if_("C_DEMO_R%d" % r)
        p.rect_c(7, y - 1, 66, 3, (35, 45, 78), border=LBLUE)
        p.text_c(8, y, ">", GOLD)
        p.text_c(61, y, "[APPLY]", GREEN)
        p.end(at)
        p.text_c(10, y, lbl, GOLD)
        p.text_c(21, y, "<", LBLUE)
        if tbl:
            p.strsel_c(23, y, tbl, fld, WHITE)
        else:
            p.field_c(23, y, fld, WHITE, 10)
        p.text_c(57, y, ">", LBLUE)

    p.strsel_c(40, 35, "T_DEMO_NOTE", "F_DEMO_NOTE", GREEN, center=True)
    p.text_c(40, 39, "BTNU/D:Row | BTNL/R:Option | BTNC:Apply | SW12:Close", LBLUE, center=True)
