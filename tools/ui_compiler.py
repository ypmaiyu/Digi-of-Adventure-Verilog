#!/usr/bin/env python3
"""
ui_compiler.py - builds the text/UI layer data for the FPGA.

    python3 fpga/tools/ui_compiler.py            (run from the repository root)

Outputs
    fpga/mem/font.mem      128 glyphs x 8 rows (8 bit)
    fpga/mem/ui_prog.mem   painter program ROM (32 bit words)
    fpga/mem/ui_str.mem    string ROM (8 bit ASCII, 0 terminated, 0x0A = new line)
    fpga/rtl/gen/ui_ids.vh field / condition / program / table-entry constants
    fpga/rtl/gen/ui_pal.vh 32-entry UI colour table (RGB444)
The painter model at the bottom (paint()) is the reference the RTL is checked against.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from uilib import UI, KEEP
import font8x8
import screens_common, screens_s1
try:
    import screens_flow
except ImportError:
    screens_flow = None
try:
    import screens_s2
except ImportError:
    screens_s2 = None
try:
    import screens_s3
except ImportError:
    screens_s3 = None

ROOT = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.getcwd()
FPGA = ROOT if os.path.isdir(os.path.join(ROOT, "rtl")) else os.path.join(ROOT, "fpga")


def build():
    ui = UI()
    descs = screens_s1.card_descs_s1()
    if screens_s2:
        descs += screens_s2.card_descs_s2()
    bar_titles = [("NONE", ""), ("OPEN", "DIGI OF ADVENTURE"), ("S1", "STAGE 1 - FINAL EXAM (Room CPE1119)"),
                  ("C12", "STAGE 1 CLEAR"), ("S2", "STAGE 2 - INTERNSHIP"), ("C23", "STAGE 2 CLEAR"),
                  ("S3", "STAGE 3 - GRADUATION RUN"), ("END", "GRADUATION")]
    ui.table("T_BAR_TITLE", bar_titles)
    ui.table("T_BAR_HELP", [
        ("NONE", ""),
        ("OPEN", "BTNC: next   BTNL: back   BTND: skip to Stage 1"),
        ("S1",   "Arrows:Move | BTNC:Act(hold:Back) | SW0-7:Input | SW14:Notes | SW15:Help"),
        ("CUT",  "BTNC: next"),
        ("S2",   "Arrows:Move | BTNC:Act(hold:Back) | SW0-2:Test | SW13:Skill | SW14/15:Tab"),
        ("S3",   "BTNL/R:Move | BTNU:Jump (tap:Double Jump) | BTNC:Skill | BTND:Pause"),
        ("END",  "BTNC: next   BTNL: back"),
    ])
    screens_common.build_common(ui, descs)
    screens_s1.build_s1(ui)
    if screens_flow:
        screens_flow.build_flow(ui)
    if screens_s2:
        screens_s2.build_s2(ui)
    if screens_s3:
        screens_s3.build_s3(ui)
    return ui


def vname(s):
    return "".join(c if c.isalnum() else "_" for c in s).upper()


def write(ui):
    rom, table_addr = ui.link()
    os.makedirs(os.path.join(FPGA, "mem"), exist_ok=True)
    os.makedirs(os.path.join(FPGA, "rtl", "gen"), exist_ok=True)
    if len(rom) > 4096:
        raise SystemExit("UI program ROM too big: %d words" % len(rom))
    if len(ui.strings.data) > 32768:
        raise SystemExit("UI string ROM too big: %d bytes" % len(ui.strings.data))
    with open(os.path.join(FPGA, "mem", "ui_prog.mem"), "w") as f:
        f.write("// ui_prog: %d x 32 bit (generated by ui_compiler.py)\n" % len(rom))
        for v in rom:
            f.write("%08X\n" % v)
    with open(os.path.join(FPGA, "mem", "ui_str.mem"), "w") as f:
        f.write("// ui_str: %d x 8 bit\n" % len(ui.strings.data))
        for b in ui.strings.data:
            f.write("%02X\n" % b)
    g = font8x8.glyphs()
    with open(os.path.join(FPGA, "mem", "font.mem"), "w") as f:
        f.write("// font: 128 glyphs x 8 rows, bit 7 = left pixel\n")
        for rows in g:
            for v in rows:
                f.write("%02X\n" % v)
    with open(os.path.join(FPGA, "rtl", "gen", "ui_ids.vh"), "w") as f:
        f.write("// generated by fpga/tools/ui_compiler.py - do not edit\n")
        for n, i in ui.reg.progs.items():
            f.write("localparam [7:0] P_%s = 8'd%d;\n" % (vname(n), i))
        for n, i in ui.reg.fields.items():
            f.write("localparam [7:0] %s = 8'd%d;\n" % (vname(n), i))
        for n, i in ui.reg.conds.items():
            f.write("localparam [7:0] %s = 8'd%d;\n" % (vname(n), i))
        for t, entries in ui.tables.items():
            for k, (key, _) in enumerate(entries):
                f.write("localparam [15:0] %s_%s = 16'd%d;\n" % (vname(t), vname(key), k))
        f.write("localparam UI_NPROG = %d;\n" % (len(ui.programs) + 1))
    with open(os.path.join(FPGA, "rtl", "gen", "ui_pal.vh"), "w") as f:
        f.write("// generated by fpga/tools/ui_compiler.py - 32 UI colours, RGB444\n")
        f.write("function [11:0] ui_pal;\n  input [4:0] i;\n  begin\n    case (i)\n")
        for i, (r, gg, b) in enumerate(ui.pal.cols):
            f.write("      5'd%d: ui_pal = 12'h%X%X%X;\n" % (i, r, gg, b))
        f.write("      default: ui_pal = 12'h000;\n    endcase\n  end\nendfunction\n")
    return rom


# ------------------------------------------------------------------------------------------
# reference model of rtl/video/ui_painter.v + text layer output
# ------------------------------------------------------------------------------------------
def paint(ui, rom, prog_names, field=lambda name, i: 0, fval=lambda name: 0, cond=lambda name: False):
    """Runs the painter. Returns 45x80 grid of (glyph, fg, bg, big, qx, qy)."""
    inv_f = {v: k for k, v in ui.reg.fields.items()}
    inv_c = {v: k for k, v in ui.reg.conds.items()}
    S = ui.strings.data
    cells = [[(0, 0, 0, 0, 0, 0) for _ in range(80)] for _ in range(45)]

    def put(c, r, glyph, fg, bg, big=0, qx=0, qy=0):
        if 0 <= c < 80 and 0 <= r < 45:
            old = cells[r][c]
            cells[r][c] = (glyph, fg, old[2] if bg == KEEP else bg, big, qx, qy)

    def draw_chars(c, r, chars, fg, bg, big):
        w = 2 if big else 1
        for k, ch in enumerate(chars):
            if big:
                for qy in (0, 1):
                    for qx in (0, 1):
                        put(c + k * w + qx, r + qy, ch, fg, bg, 1, qx, qy)
            else:
                put(c + k, r, ch, fg, bg)

    def field_chars(fid, maxlen):
        name = inv_f[fid]
        out = []
        for i in range(maxlen):
            ch = field(name, i)
            if not ch:
                break
            out.append(ch)
        return out

    for name in prog_names:
        pc = rom[ui.reg.progs[name]]
        ox = oy = 0
        cur = 0
        while True:
            w = rom[pc]
            op = w >> 28
            if op == 0:
                break
            col = ((w >> 21) & 0x7F) + ox
            row = ((w >> 15) & 0x3F) + oy
            fg, big, center, flow, lstep, bg = (w >> 10) & 31, (w >> 9) & 1, (w >> 8) & 1, (w >> 7) & 1, ((w >> 5) & 3) + 1, w & 31
            if op == 1:
                w1 = rom[pc + 1]
                ww, hh = w1 & 0x7F, (w1 >> 8) & 0x3F
                border = (w >> 9) & 1
                dither = (w >> 8) & 1
                for r in range(row, row + hh):
                    for c in range(col, col + ww):
                        g = 0
                        if dither:
                            g = 0x07
                        if border:
                            top, bot, lef, rig = r == row, r == row + hh - 1, c == col, c == col + ww - 1
                            g = (0x08 if top and lef else 0x09 if top and rig else 0x0A if bot and lef else
                                 0x0B if bot and rig else 0x0C if top else 0x0D if bot else 0x0E if lef else
                                 0x0F if rig else g)
                        if g or bg != KEEP:
                            put(c, r, g, fg, bg)
                pc += 2
            elif op in (2, 3, 7, 8):
                w1 = rom[pc + 1]
                if op == 2 or op == 7:
                    if op == 2:
                        a = w1 & 0xFFFF
                    else:
                        a = rom[(w1 & 0xFFFF) + fval(inv_f[(w1 >> 16) & 0xFF])] & 0xFFFF
                    text = []
                    while S[a]:
                        text.append(S[a])
                        a += 1
                    lines = bytes(text).split(b"\n")
                elif op == 3:
                    lines = [bytes(field_chars(w1 & 0xFF, (w1 >> 8) & 0xFF))]
                else:
                    lines = [bytes([w1 & 0xFF] * ((w1 >> 8) & 0x7F))]
                r = cur if flow else row
                for ln in lines:
                    c = col - (len(ln) * (2 if big else 1)) // 2 if center else col
                    if ln:
                        draw_chars(c, r, list(ln), fg, bg, big)
                    r += lstep * (2 if big else 1)
                if flow and any(lines):
                    cur = r
                pc += 2
            elif op in (4, 5):
                cv = cond(inv_c[(w >> 20) & 0xFF])
                n = w & 0xFFF
                pc += 1
                if (op == 4 and not cv) or (op == 5 and cv):
                    pc += n
            elif op == 6:
                fx, fy = (w >> 20) & 0xFF, (w >> 12) & 0xFF
                sx = 0 if fx == 0xFF else fval(inv_f[fx])
                sy = 0 if fy == 0xFF else fval(inv_f[fy])
                ox, oy = sx, sy
                pc += 1
            elif op == 9:
                cur = (w >> 15) & 0x3F
                pc += 1
            else:
                raise ValueError("bad op %d" % op)
    return cells


def render(ui, cells, under=None):
    """text layer -> 640x360 PIL image (optionally over a background picture)."""
    from PIL import Image
    g = font8x8.glyphs()
    img = under.copy() if under is not None else Image.new("RGB", (640, 360), (18, 20, 26))
    px = img.load()
    pal = [(r * 17, gg * 17, b * 17) for (r, gg, b) in ui.pal.cols] + [(0, 0, 0)] * 32
    for r in range(45):
        for c in range(80):
            glyph, fg, bg, big, qx, qy = cells[r][c]
            for y in range(8):
                for x in range(8):
                    if big:
                        gx, gy = (qx * 8 + x) // 2, (qy * 8 + y) // 2
                    else:
                        gx, gy = x, y
                    on = (g[glyph & 127][gy] >> (7 - gx)) & 1
                    if on:
                        px[c * 8 + x, r * 8 + y] = pal[fg]
                    elif bg:
                        px[c * 8 + x, r * 8 + y] = pal[bg]
    return img


if __name__ == "__main__":
    ui = build()
    rom = write(ui)
    if screens_flow:
        screens_flow.write_confetti(os.path.join(FPGA, "rtl", "gen", "confetti.vh"))
    print("UI: %d programs, %d fields, %d conditions, %d string bytes, %d program words, %d colours"
          % (len(ui.programs), len(ui.reg.fields), len(ui.reg.conds), len(ui.strings.data), len(rom), len(ui.pal.cols)))
